public class IncrementDecrement {
    public static void main(String[]args){

        //Increment
        int num1=7;
        int result1 =++num1;
        System.out.println("Pre increment : " +result1);

        int num2=7;
        int result2 =num2++;
        System.out.println("Post increment : " +result2);

        //Decerement
        int num3=7;
        int result3 =--num3;
        System.out.println("Pre decrement : " +result3);

        int num4=7;
        int result4 =num4--;
        System.out.println("Post decrement : " +result4);

    }
}
